// Package luoshu 实现洛书 LuoShu-512 密码学哈希算法。
//
// # 算法概述
//
// 洛书 LuoShu-512 是一个输出 512 位摘要的宽管道 Merkle–Damgård 哈希，
// 状态为 3×3 九宫，每宫 128 位（阴阳双爻，Go 中用两个 uint64 表示，
// 模加经 bits.Add64 进位链构成真 128 位算术），总状态 1152 位。
//
// 结构参数：
//
//	消息分组    1024 位（128 字节, 16 个 64 位字, 大端序）
//	主轮数      72 轮 + 9 轮常数收尾 = 81 轮
//	每轮活跃    3 条幻线（8 条幻线按 (3r mod 8) 循环选取, 每线 3 宫）
//	位置置换    每 8 轮执行 σ = (0 4 8 1 5 2 6 3 7), 72 轮恰 9 次,
//	             σ⁹ = 恒等, 每个字恰好遍历全部 9 个宫位
//	消息扩展    16 字 → 432 字, σ0/σ1 沿用 SHA-512 已验证常数
//	轮常数      243 个 = 前 243 个素数立方根小数 × 2^64
//	IV          18 字 = 前 18 个素数平方根小数 × 2^64
//	抗长度扩展  HAIFA 式分组计数器每块注入中宫 + 终局标志 + 收尾轮再注入消息长度
//
// 轮函数为 BLAKE2 风格 ARX（模 2^64 加 / 异或 / 循环移位），
// 旋转量表 {5,7,13,23,31,43,47,53,61} 经全约束机器搜索选出：
// 无互补对（x+y=64）、无等差三元组、无倍数对、无倍角关系、无半周期，
// 并由单元测试永久断言。
//
// # 输出形式
//
// 512 位摘要 D 有三种表示：
//
//	hex      128 个十六进制字符（含校验无关的完整 D）
//	汉字     44 个高频汉字（D 的低 484 位, 每字 11 bit, 均匀随机映射到
//	          2048 字表的固定双射; 表为六亿知乎语料字频前 2048 字, 已冻结）
//	校验码   28 位（D 低 484 位的折叠函数, 7 个 hex 字符, 用于汉字抄写检错,
//	          属工程特性, 不构成额外密码学安全层）
//
// 汉字解码可无损还原 484 位；44 字 + 7 位校验 hex 可离线自检。
//
// # 安全声明（必须阅读）
//
// 本算法为工程级设计与实证：全部可机器验证的攻击套件（雪崩、生日、
// 原像、长度扩展、差分缩减轮、Joux 多碰撞、百万级随机搜索）均随源码
// 开源供独立复现。但在获得至少两个独立第三方的密码分析之前，
// 本算法不得用于任何生产安全场景。
//
